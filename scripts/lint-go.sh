#!/bin/sh
# Format check and lint for the Go module; generated code is excluded by .golangci.yml.
set -eu
cd "$(git rev-parse --show-toplevel)"
golangci-lint fmt --diff ./...
golangci-lint run ./...
# Again with the test only tag, so the berth_e2e files are linted too.
golangci-lint run --build-tags berth_e2e ./...
